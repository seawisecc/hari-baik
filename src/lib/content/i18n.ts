export type MessageKey = keyof (typeof dict)["id"];

/**
 * Terjemahkan satu kunci.
 *
 * Jatuh ke bahasa Indonesia bila kuncinya belum diterjemahkan, lalu ke kunci
 * itu sendiri bila memang tidak ada. Kunci yang bocor ke layar lebih mudah
 * dilihat daripada teks kosong.
 *
 * `nilai` mengisi penanda `{nama}` di dalam teks, supaya urutan kata bisa
 * berbeda antar bahasa tanpa memecah kalimatnya jadi potongan.
 */
export function translate(
  lang: Lang,
  key: MessageKey | string,
  nilai?: Record<string, string | number>,
): string {
  const table = dict[lang] as Record<string, string>;
  let teks = table?.[key] ?? (dict.id as Record<string, string>)[key] ?? String(key);
  if (nilai) {
    for (const [k, v] of Object.entries(nilai)) {
      teks = teks.replaceAll(`{${k}}`, String(v));
    }
  }
  return teks;
}

